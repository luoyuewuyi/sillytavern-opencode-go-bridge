import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { RELEASE_FILES } from '../install/layout.mjs';
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const files = {};
for (const name of RELEASE_FILES) files[name] = createHash('sha256').update(await readFile(join(root, name))).digest('hex');
await writeFile(join(root, 'release-manifest.json'), JSON.stringify({ schema: 1, version: pkg.version, files }, null, 2) + '\n');
console.log(`Prepared ${pkg.version} integrity manifest (${RELEASE_FILES.length} files). This is an integrity check, not a publisher signature.`);
